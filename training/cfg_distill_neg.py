"""Negative-prompt CFG distillation (Meng et al. style w-conditioned student) for SD1.4.

Teacher target (per sample):
    eps_pos = ref_unet(x_t, t, c)           # positive prompt
    eps_neg = ref_unet(x_t, t, c-)          # random-removal negative prompt
    eps_CFG_neg = eps_neg + s * (eps_pos - eps_neg)
                = eps_pos + lambda * (eps_pos - eps_neg)   with s = 1 + lambda

Student loss:
    L = || student_unet(x_t, t, c; w) - sg[eps_CFG_neg] ||^2

Student is w-conditioned: the SD1.4 UNet is rebuilt with `time_cond_proj_dim`
so that an additional sinusoidal embedding of the guidance scale `s` is added
to the time embedding (the same trick used in LCM-LoRA training).

Positive image latents come from a pre-encoded latent dataset
(e.g. data/latents/diffusiondb_llama_200k); negative prompts come from the
`neg_prompt` / `all_neg_prompts` fields of the same metadata
(generated by prompts_generation/DiffusionDB_random_removal.py).
"""

