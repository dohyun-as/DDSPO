# ---------------------------------------------------------------------------
# Guidance-scale embedding (LCM / Meng et al. style)
# ---------------------------------------------------------------------------
def guidance_scale_embedding(w, embedding_dim=256, dtype=torch.float32):
    """Sinusoidal embedding of a guidance scale `w`.

    Computed in fp32 internally (sin/cos of values up to ~7000 is unsafe in
    fp16) and cast to `dtype` only at the end. Matches diffusers' LCM helper.
    Input  : w of shape (B,) — guidance scale per sample.
    Output : (B, embedding_dim) in `dtype`.
    """
    assert w.ndim == 1
    w_fp32 = w.float() * 1000.0
    half_dim = embedding_dim // 2
    freq = math.log(10000.0) / (half_dim - 1)
    freq = torch.exp(torch.arange(half_dim, dtype=torch.float32, device=w.device) * -freq)
    emb = w_fp32[:, None] * freq[None, :]
    emb = torch.cat([torch.sin(emb), torch.cos(emb)], dim=1)
    if embedding_dim % 2 == 1:
        emb = F.pad(emb, (0, 1))
    return emb.to(dtype)


